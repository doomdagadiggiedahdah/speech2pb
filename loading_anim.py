class LoadingAnimation:
    def __init__(self, text="Loading", anim_name=None, stream=sys.stderr):
        if anim_name is None:
            anim_name = random.choice(list(ANIMATIONS))
        self._text = text
        self._frames = ANIMATIONS[anim_name]
        self._stream = stream
        self._stop = threading.Event()
        self._thread = None

    def _run(self):
        i = 0
        max_len = max(len(f) for f in self._frames)
        while not self._stop.is_set():
            frame = self._frames[i % len(self._frames)]
            line = f"\r{self._text}  {frame:<{max_len}}"
            self._stream.write(line)
            self._stream.flush()
            i += 1
            self._stop.wait(0.3)
        # Clear the animation line
        self._stream.write(f"\r{' ' * (len(self._text) + max_len + 4)}\r")
        self._stream.flush()

    def __enter__(self):
        self._thread = threading.Thread(target=self._run, daemon=True)
        self._thread.start()
        return self

    def __exit__(self, *exc):
        self._stop.set()
        self._thread.join()


if __name__ == "__main__":
    duration = float(sys.argv[1]) if len(sys.argv) > 1 else 5.0
    for name in ANIMATIONS:
        print(f"\n--- {name} ---", file=sys.stderr)
        with LoadingAnimation("Loading model", anim_name=name):
            time.sleep(duration)
    print("\nDone!", file=sys.stderr)
